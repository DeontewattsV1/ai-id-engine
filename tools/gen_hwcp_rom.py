"""Generate rtl/hwcp_rom.v: the boot-ROM "hardware code page".

The code page is the printable ASCII half of IBM code page 437 (0x20-0x7E)
as 8x8 glyphs taken from the public-domain font8x8_basic.h (tools/hwcp/).
It lets the engine (or a boot UART console) draw characters before any OS
font exists. Also emits a fixed 32-character boot banner.

Glyph byte layout: one byte per row, row 0 at the top, bit 0 = leftmost
pixel (same as font8x8_basic). Address = (char - 0x20) * 8 + row.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
BANNER = "AI-ID ENGINE v0.1.0 BOOT ROM    "
assert len(BANNER) == 32


def load_font():
    src = (ROOT / "tools/hwcp/font8x8_basic.h").read_text()
    rows = re.findall(r"\{\s*((?:0x[0-9A-Fa-f]{2},?\s*){8})\}", src)
    glyphs = [[int(b, 16) for b in re.findall(r"0x([0-9A-Fa-f]{2})", r)] for r in rows]
    assert len(glyphs) == 128, len(glyphs)
    return glyphs


def main():
    g = load_font()
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// GENERATED by tools/gen_hwcp_rom.py - do not edit.",
        "// Boot ROM hardware code page: CP437 printable half (0x20-0x7E), 8x8",
        "// glyphs from the public-domain font8x8_basic, plus the boot banner.",
        "`timescale 1ns/1ps",
        "",
        "module hwcp_rom (",
        "    input  wire [9:0] glyph_addr,   // (char - 0x20) * 8 + row",
        "    output reg  [7:0] glyph_byte,",
        "    input  wire [2:0] banner_word,  // 8 words of 4 ASCII chars",
        "    output reg  [31:0] banner",
        ");",
        "    always @(*) begin",
        "        case (glyph_addr)",
    ]
    for c in range(0x20, 0x7F):
        for r in range(8):
            a = (c - 0x20) * 8 + r
            lines.append(f"            10'd{a}: glyph_byte = 8'h{g[c][r]:02x};")
    lines += ["            default: glyph_byte = 8'h00;", "        endcase", "    end", "",
              "    always @(*) begin", "        case (banner_word)"]
    for w in range(8):
        chunk = BANNER[4 * w:4 * w + 4].encode()
        lines.append(f"            3'd{w}: banner = 32'h{chunk.hex()};  // \"{BANNER[4*w:4*w+4]}\"")
    lines += ["            default: banner = 32'h0;", "        endcase", "    end", "endmodule", ""]
    (ROOT / "rtl/hwcp_rom.v").write_text("\n".join(lines))
    print("wrote rtl/hwcp_rom.v (95 glyphs, 760 bytes + 32-byte banner)")


if __name__ == "__main__":
    main()
