"""Emit mont_params.vh. Run once; output is checked in."""
P = 2**256 - 2**224 + 2**192 + 2**96 - 1
N = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551

def n0prime(m):
    """-m^-1 mod 2^32, Newton iteration."""
    x = 1
    for _ in range(5):                    # 1 -> 2 -> 4 -> 8 -> 16 -> 32 bits
        x = (x * (2 - m * x)) & 0xFFFFFFFF
    assert (m * x) & 0xFFFFFFFF == 1
    return (-x) & 0xFFFFFFFF

def words(v, n=8):
    return [(v >> (32 * i)) & 0xFFFFFFFF for i in range(n)]

R = 2**256 % P
R2P = (2**512) % P
R2N = (2**512) % N
RN = (2**256) % N

lines = ["// AUTO-GENERATED by gen_mont_constants.py - do not edit",
         "`ifndef MONT_PARAMS_VH", "`define MONT_PARAMS_VH",
         f"localparam [255:0] P_MOD = 256'h{P:064x};",
         f"localparam [255:0] N_MOD = 256'h{N:064x};",
         f"localparam [31:0]  P_N0  = 32'h{n0prime(P):08x};",
         f"localparam [31:0]  N_N0  = 32'h{n0prime(N):08x};",
         f"localparam [255:0] P_R2  = 256'h{R2P:064x};",
         f"localparam [255:0] N_R2  = 256'h{R2N:064x};",
         f"localparam [255:0] P_R   = 256'h{R:064x};",
         f"localparam [255:0] N_R   = 256'h{RN:064x};",
         "`endif"]
open("rtl/mont_params.vh", "w").write("\n".join(lines) + "\n")
print("wrote rtl/mont_params.vh")
print(f"p n0' = {n0prime(P):08x}   n n0' = {n0prime(N):08x}")
