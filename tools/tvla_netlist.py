#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Build the power-instrumented gate-level netlist for the TVLA harness.

Input: the sky130-mapped Yosys JSON netlist and build/lib.json.
Output:
  OUT.v     module `tvla_dut`: the same cells and ports, every net renamed to
            n<bit>, plus `output [N-1:0] pw_bits` exposing every switching
            net, so the harness can count toggles per net per cycle.
  OUT.json  {"caps_pf": [pF per pw_bits index], "names": [...], ...}
  OUT.caps  the same capacitances as raw float64, read by tb/tvla_harness.cpp

Net capacitance = sum of the input-pin capacitances the net drives (from the
.lib) + the default wire-load model's estimate for its fanout (from the .lib)
+ a fixed external load on primary outputs. This is a pre-layout estimate.
There is no extraction, so treat absolute energies as order-of-magnitude
only. TVLA needs only relative, data-dependent differences.
"""
import argparse, json, struct, sys

OUT_PORT_LOAD_PF = 0.005   # assumed external load on each primary output bit


def wire_cap(lib, fanout):
    wl = lib["wire_load"].get(lib.get("default_wire_load") or "", None)
    if not wl or fanout <= 0:
        return 0.0
    fl = {int(k): v for k, v in wl["fanout_length"].items()}
    top = max(fl)
    length = fl[fanout] if fanout in fl else fl[top] + wl["slope"] * (fanout - top)
    return wl["capacitance"] * length


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("netlist_json"); ap.add_argument("lib_json")
    ap.add_argument("out_v"); ap.add_argument("out_json")
    ap.add_argument("--top")
    a = ap.parse_args()
    nl = json.load(open(a.netlist_json)); lib = json.load(open(a.lib_json))
    mods = nl["modules"]
    top = a.top or next(n for n, m in mods.items()
                        if m.get("attributes", {}).get("top"))
    m = mods[top]

    def ref(bit):
        if bit in ("0", "1"):
            return f"1'b{bit}"
        if bit in ("x", "z"):
            return "1'b0"
        return f"n{bit}"

    bits, cap, fanout = set(), {}, {}
    names = {}
    for nn, info in m["netnames"].items():
        hidden = info.get("hide_name", 0)
        for i, b in enumerate(info["bits"]):
            if isinstance(b, int) and (b not in names or (not hidden and names[b][1])):
                label = nn if len(info["bits"]) == 1 else f"{nn}[{i}]"
                names[b] = (label, hidden)
    for cname, c in m["cells"].items():
        ct = c["type"]
        if ct not in lib["cells"]:
            sys.exit(f"cell {ct} not in liberty")
        pins = lib["cells"][ct]["pins"]
        for pin, conn in c["connections"].items():
            for b in conn:
                if not isinstance(b, int):
                    continue
                bits.add(b)
                p = pins.get(pin)
                if p and p["dir"] == "input":
                    cap[b] = cap.get(b, 0.0) + p["cap"]
                    fanout[b] = fanout.get(b, 0) + 1
    for pname, p in m["ports"].items():
        for b in p["bits"]:
            if isinstance(b, int):
                bits.add(b)
                if p["direction"] == "output":
                    cap[b] = cap.get(b, 0.0) + OUT_PORT_LOAD_PF
    order = sorted(bits)
    caps = [cap.get(b, 0.0) + wire_cap(lib, fanout.get(b, 0)) for b in order]

    out = []
    w = out.append
    w("// SPDX-License-Identifier: MIT")
    w(f"// GENERATED by tools/tvla_netlist.py from {a.netlist_json}; do not edit.")
    w("`timescale 1ns/1ps")
    plist = list(m["ports"].keys())
    w(f"module tvla_dut({', '.join(plist + ['pw_bits'])});")
    for pname, p in m["ports"].items():
        width = len(p["bits"])
        rng = f"[{width-1}:0] " if width > 1 else ""
        w(f"  {p['direction']} {rng}{pname};")
    w(f"  output [{len(order)-1}:0] pw_bits;")
    port_bits = {}
    for pname, p in m["ports"].items():
        for i, b in enumerate(p["bits"]):
            if isinstance(b, int):
                port_bits.setdefault(b, []).append((pname, i, len(p["bits"]), p["direction"]))
    for b in order:
        w(f"  wire n{b};")
    for pname, p in m["ports"].items():
        width = len(p["bits"])
        for i, b in enumerate(p["bits"]):
            sel = f"{pname}[{i}]" if width > 1 else pname
            if p["direction"] == "input":
                w(f"  assign n{b} = {sel};")
            else:
                w(f"  assign {sel} = {ref(b) if isinstance(b, int) else ref(str(b))};")
    for idx, (cname, c) in enumerate(sorted(m["cells"].items())):
        conns = []
        for pin, conn in c["connections"].items():
            b = conn[0]
            conns.append(f".{pin}({ref(b) if isinstance(b, int) else ref(str(b))})")
        w(f"  {c['type']} c{idx} ({', '.join(conns)});")
    # One bit per line: Verilator limits tokens per source line.
    for i, b in enumerate(order):
        w(f"  assign pw_bits[{i}] = n{b};")
    w("endmodule")
    open(a.out_v, "w").write("\n".join(out) + "\n")

    nz = [c for c in caps if c > 0]
    meta = {"top": top, "nets": len(order), "caps_pf": caps, "bits": order,
            "names": [names.get(b, (f"n{b}", 1))[0] for b in order],
            "total_cap_pf": sum(caps),
            "min_cap_pf": min(nz), "max_cap_pf": max(nz),
            "vdd": lib["nom_voltage"], "cells": len(m["cells"]),
            "model": "pin caps + default wire_load (pre-layout)"}
    json.dump(meta, open(a.out_json, "w"))
    # Binary caps for the C++ harness: vdd (f64), nbits (u64), caps (f64 * n).
    with open(a.out_json.rsplit(".", 1)[0] + ".caps", "wb") as f:
        f.write(struct.pack("<dQ", lib["nom_voltage"], len(caps)))
        f.write(struct.pack(f"<{len(caps)}d", *caps))
    print(f"tvla_netlist {top}: {len(m['cells'])} cells, {len(order)} nets, "
          f"cap {min(nz)*1e3:.2f}..{max(nz)*1e3:.2f} fF, total {sum(caps):.2f} pF")


if __name__ == "__main__":
    main()
